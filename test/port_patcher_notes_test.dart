// Tests for the port of libYSE's long-form patcher object notes into the
// docs' object reference (tool/port_patcher_notes.dart, #78).
//
// The notes are committed under docs/source/_data/patcher_notes/ because the
// docs workflow does not check out the engine submodule. The drift test
// compares that copy with a fresh port of the submodule's notes; it needs
// the submodule checked out (CI's test job does), not a built engine.
@TestOn('vm')
library;

import 'dart:io';

import 'package:test/test.dart';

import '../tool/port_patcher_notes.dart';

const _upstreamSource = 'third_party/yse-soundengine/documentation/source';

const _upstream = UpstreamDocs(
  titles: {'/patcher/messages': 'Messages and dispatch'},
  labels: {'data-saved': ('/patcher/data', 'What is saved with the patch')},
);

String _port(String body, {Set<int>? used}) =>
    portNotes('.. upstream preamble\n\n$body', 'lists', _upstream, used: used);

String _body(String ported) =>
    ported.substring(ported.indexOf('.. patcher-object::'));

void main() {
  group('portNotes', () {
    test('replaces the preamble with a generated-file header', () {
      final out = _port('.. patcher-object:: .iter\n\nText.\n\n\n');
      expect(out, startsWith('.. Generated by tool/port_patcher_notes.dart'));
      expect(out, contains('patcher_notes/lists.rst'));
      expect(out, isNot(contains('upstream preamble')));
      expect(out, endsWith('.. patcher-object:: .iter\n\nText.\n'));
    });

    test('points category page links at the local object reference', () {
      final out = _body(
        _port(
          '.. patcher-object:: .iter\n\n'
          'See :doc:`/patcher/objects/math`, :doc:`lists` and '
          ':doc:`the list objects </patcher/objects/lists>`.',
        ),
      );
      expect(
        out,
        contains(
          'See :doc:`/api/patcher_objects/math`, '
          ':doc:`/api/patcher_objects/lists` and '
          ':doc:`the list objects </api/patcher_objects/lists>`.',
        ),
      );
    });

    test('turns upstream-only :doc: links into titled :yse-cpp: links', () {
      final out = _body(
        _port(
          '.. patcher-object:: .iter\n\n'
          'See :doc:`/patcher/messages`, or\n'
          ':doc:`dispatch </patcher/messages>`.',
        ),
      );
      expect(
        out,
        contains(
          'See :yse-cpp:`Messages and dispatch <patcher/messages.html>`, or\n'
          ':yse-cpp:`dispatch <patcher/messages.html>`.',
        ),
      );
    });

    test('turns :ref: links into anchored :yse-cpp: links', () {
      final out = _body(
        _port(
          '.. patcher-object:: .iter\n\n'
          'See :ref:`data-saved` and :ref:`saving <data-saved>`.',
        ),
      );
      expect(
        out,
        contains(
          'See :yse-cpp:`What is saved with the patch '
          '<patcher/data.html#data-saved>` and '
          ':yse-cpp:`saving <patcher/data.html#data-saved>`.',
        ),
      );
    });

    test('rejects a link target upstream does not have', () {
      expect(
        () => _port('.. patcher-object:: .iter\n\n:doc:`/patcher/nope`'),
        throwsFormatException,
      );
      expect(
        () => _port('.. patcher-object:: .iter\n\n:ref:`nope`'),
        throwsFormatException,
      );
    });

    test('rejects a role it does not know how to rewrite', () {
      expect(
        () => _port('.. patcher-object:: .iter\n\n:cpp:class:`YSE::sound`'),
        throwsFormatException,
      );
    });

    test('translates C++ host-API names to Dart and drops C asides', () {
      final used = <int>{};
      final out = _body(
        _port(
          '.. patcher-object:: .iter\n\n'
          'Until the host calls ``YSE::Randomize()``\n'
          '(``yse_randomize()`` in C). Build it with ``CreateObject``.',
          used: used,
        ),
      );
      expect(
        out,
        contains(
          'Until the host calls ``System.randomize()``. '
          'Build it with ``Patcher.createObject``.',
        ),
      );
      expect(used, hasLength(3));
    });

    test('rejects a C++ API name with no Dart equivalent', () {
      for (final cpp in [
        '``YSE::Sound().play()``',
        '``yse_sound_play()``',
        '``DeleteObject``',
        '``sound::create``',
      ]) {
        expect(
          () => _port('.. patcher-object:: .iter\n\nCall $cpp.'),
          throwsFormatException,
          reason: cpp,
        );
      }
    });

    test('keeps dictionary key paths and patch notation', () {
      const text =
          '.. patcher-object:: .dict\n\n'
          '``voice::1::freq`` is one entry.\n\n'
          '.. code-block:: text\n\n'
          '    [.metro 100] -> [.array.change steps]\n';
      expect(_body(_port(text)), text);
    });

    test('rejects a file without markers', () {
      expect(() => _port('Just text.'), throwsFormatException);
    });
  });

  group('against the engine submodule', () {
    final available = Directory(
      '$_upstreamSource/_data/patcher_notes',
    ).existsSync();
    final skip = available ? false : 'engine submodule not checked out';

    test('every C++ name in the notes has a Dart translation in use', () {
      // Throws on a stale cppToDart entry or an untranslated name.
      expect(portAllNotes(Directory(_upstreamSource)), isNotEmpty);
    }, skip: skip);

    test('every upstream link resolves to an upstream page and anchor', () {
      final upstream = UpstreamDocs.scan(Directory(_upstreamSource));
      final ported = portAllNotes(Directory(_upstreamSource));
      final link = RegExp(
        r':yse-cpp:`[^`<]*<(patcher/[\w/]+)\.html(#[\w-]+)?>`',
      );
      for (final text in ported.values) {
        for (final m in link.allMatches(text)) {
          expect(upstream.titles, contains('/${m.group(1)}'));
          if (m.group(2) case final anchor?) {
            expect(upstream.labels[anchor.substring(1)]?.$1, '/${m.group(1)}');
          }
        }
      }
    }, skip: skip);

    test(
      'the committed notes match a fresh port',
      () async {
        final r = await Process.run(Platform.resolvedExecutable, [
          'run',
          'tool/port_patcher_notes.dart',
          '--check',
        ]);
        expect(r.exitCode, 0, reason: '${r.stdout}\n${r.stderr}');
      },
      skip: skip,
      timeout: const Timeout(Duration(minutes: 3)),
    );
  });
}
